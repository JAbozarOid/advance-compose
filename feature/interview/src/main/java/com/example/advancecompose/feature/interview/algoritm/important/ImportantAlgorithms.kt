/**
 * 15 important Algorithms
 *
 * A- Searching Algorithms
 *   1- Linear search : sequentially check each item in a list or array until find the target value --> O(n)
 *   2- Binary search : works on a sorted list or array it follows divided and conquer, repeatedly the searching space in half until the target value is found --> O(log n)
 *
 * B- Sorting Algorithms
 *   1- Bubble sort : repeatedly swap two adjacent elements if they are in the wrong order --> O(n^2)
 *   2- Insertion sort : O(n^2)
 *   3- Selection sort : divide the input list into two parts : sorted at the beginning and unsorted at the end, it repeatedly select the smallest element from the unsorted part and move it to the sorted part -->O(n^2)
 *   4- Heap sort : use a binary heap to sort the list  O(n log n)
 *   5- Merge sort : is recursive that follows divide and conquer principle, it divide the input list into smaller and sort them independently --> O(n log n)
 *   6- Quick sort : is a comparison based that follow divide and conquer principle --> O(n log n)
 *
 * /////////////////////////////
 *
 * B- Graph Algorithms
 *   1- Breadth-first search : is an algorithm for searching a tree data structure for a node that satisfies a given property. It starts at the tree root and explores all nodes at the present depth prior to moving on to the nodes at the next depth level O(V + E)
 *   2- Depth-first search : is an algorithm for traversing or searching tree or graph data structures,The algorithm starts at the root node and explores as far as possible along each branch before backtracking. --> O(V + E)
 *   3- Dijkstra's algorithm : is an algorithm for finding the shortest paths between nodes in a weighted graph, which may represent, for example, road networks --> O ( V + E log V )
 *   4- Kadane’s Algorithm: is an efficient algorithm used to find the maximum sum of a contiguous subarray within a given array of numbers --> O(n)
 *
 * C- Tree Algorithms
 *   1- Inorder Traversal : O(n)
 *   2- Preorder Traversal: O(n)
 *   3- Postorder Traversal: O(n)
 */